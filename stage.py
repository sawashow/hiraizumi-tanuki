def thin_dango(items, platforms):
    """団子を間引く。団子は、手裏剣を投げられる数を増やす物になったので、数を絞る（画面に、物が多すぎないように）。
    **足場の上の団子だけを残す（足場1つに、1つ）。地面に置いた団子は、すべて外す。**
    足場に乗る理由が、団子になる（団子を外した足場は、乗る意味が無くなる）。ほかのアイテムは、そのまま"""
    out, used = [], set()
    for it in items:
        if it[0] != "dango":
            out.append(it)
            continue
        on = [p for p in platforms if p[0] - 6 <= it[1] <= p[1] + 6 and 0 < p[2] - it[2] <= 60]
        if on and on[0] not in used:
            used.add(on[0])
            out.append(("dango", (on[0][0] + on[0][1]) // 2, it[2]))    # 足場の真ん中に置く
    return tuple(out)


def split_intent(rows):
    """配置の各行の、末尾の「意図」（文字列）を切り分ける。(意図を外した行の並び, 意図の並び)。意図の無い行は ""。
    敵・足場・動く足場・消える足場・区画は、行の最後に、その置き方の意図を書ける（tools/stage_intent.py が一覧にする）"""
    out, notes = [], []
    for r in map(tuple, rows):
        has = len(r) > 2 and isinstance(r[-1], str)    # 区画は (左端, 右端, 名前, 役目, ねらい[, 意図])。ねらいは数なので、意図と取り違えない
        out.append(r[:-1] if has else r)
        notes.append(r[-1] if has else "")
    return tuple(out), tuple(notes)


class StageDef:
    """1つの面のデータ。地形・アイテム・敵・ボス・背景・曲を、1つにまとめる。
    絵は assets/images 以下の相対パス。面ごとの絵が無ければ、1面の絵で代わりにする"""

