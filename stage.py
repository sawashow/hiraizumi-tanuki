def _run(parts, x=0):
    """区間の並びから、地面（x0, x1, 高さ）を作る。parts の各項目は、(幅, 床からの高さ) か、("穴", 幅)。
    (地面の区間の並び, 終わりの x) を返す"""
    out = []
    for part in parts:
        if part[0] == "穴":
            x += part[1]
            continue
        w, up = part
        out.append((x, x + w, T - up))
        x += w
    return tuple(out), x

