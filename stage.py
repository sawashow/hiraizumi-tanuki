class Terrain:
    FOOT = 6   # 足元の判定の、中心から左右への幅（端に少しかかっていれば立てる）

    def __init__(self, ground=GROUND, platforms=PLATFORMS, climb=None, blinks=(), movers=()):
        self.ground = [tuple(g) for g in ground]
        self.platforms = [tuple(p) for p in platforms]
        # 動く足場: (左端 ax, 上面 ay, 左端 bx, 上面 by, 幅, ずれ[, 往復のフレーム数])。A と B の間を往復する。横にも縦にも斜めにも動ける
        self.movers = [tuple(m) for m in movers]
        self.mover_now = []     # いまの位置 (x0, x1, 上面)（move が、毎フレーム入れ直す）
        self.mover_prev = []    # 1フレーム前の位置
        self.move(0)
        # 消える光の足場: (x0, x1, 上面の高さ, ずれ)。点いたり消えたりする（config.BLINK）。ずれは、一巡りの中の、始まりのフレーム
        self.blinks = [tuple(b) for b in blinks]
        self.lit = []       # いま、乗れる光の足場（tick が、毎フレーム入れ直す）
        self.tick(0)
        # 崖登り: (左端, 右端, 高さ)。右端より手前は、高さのぶん、低い所にある（面の絵が、そのぶん縦に長い）。
        # 左端〜右端の間だけ、画面が上下に動く。右端から先は、ふつうの高さ
        self.climb = tuple(climb) if climb else None

    @property
    def world_h(self):
        """面の絵の高さ（崖登りが無ければ、画面と同じ）"""
        return C.BASE_H + (self.climb[2] if self.climb else 0)

    def depth_at(self, x):
        """x の所が、ふつうの高さより、どれだけ低い所にあるか（崖の手前は、崖の高さぶん。穴の底・落ちた判定を、そのぶん下げる）"""
        return self.climb[2] if self.climb and x < self.climb[1] else 0

    def blink_state(self, b, t):
        """光の足場 b の、時刻 t の状態: on（乗れる）/ warn（乗れる。もうすぐ消える）/ off（消えている）"""
        k = (t + b[3]) % C.BLINK["period"]
        return "on" if k < C.BLINK["on"] - C.BLINK["warn"] else "warn" if k < C.BLINK["on"] else "off"

    def tick(self, t):
        self.lit = [b[:3] for b in self.blinks if self.blink_state(b, t) != "off"]

    @staticmethod
    def mover_at(m, t):
        """動く足場 m の、時刻 t の位置 (x0, x1, 上面)。両端で少し止まり、動くときは、ゆっくり始まってゆっくり止まる"""
        ax, ay, bx, by, w, shift = m[:6]
        period = m[6] if len(m) > 6 else C.MOVER["period"]
        k = ((t + shift) % period) / period
        u = k * 2 if k < 0.5 else 2 - k * 2          # 0 → 1 → 0
        d = C.MOVER["dwell"]
        s = min(1.0, max(0.0, (u - d) / (1 - 2 * d)))
        s = s * s * (3 - 2 * s)
        x = ax + (bx - ax) * s
        return (round(x), round(x) + w, round(ay + (by - ay) * s))

    def move(self, t):
        """動く足場を、時刻 t の位置にする（1フレーム前の位置も覚えておく。乗っている人を運ぶのに使う）"""
        self.mover_prev = self.mover_now or [self.mover_at(m, t) for m in self.movers]
        self.mover_now = [self.mover_at(m, t) for m in self.movers]

    def rider(self, px, py):
        """(px, py) に立っている人が乗っている、動く足場が、1フレームで動いた量 (dx, dy)。乗っていなければ None"""
        for (x0, x1, top), (p0, p1, ptop) in zip(self.mover_now, self.mover_prev):
            if p0 - self.FOOT < px < p1 + self.FOOT and abs(py - ptop) <= 1.5:
                return x0 - p0, top - ptop
        return None

    def height_at(self, x):
        """x にある地面の上面の高さ（一番高いもの）。地面がなければ None"""
        tops = [top for a, b, top in self.ground if a <= x < b]
        return min(tops) if tops else None

    def ground_at(self, x0, x1):
        """x0〜x1 に、地面が少しでもあるか"""
        return any(a < x1 and x0 < b for a, b, _ in self.ground)

    def support(self, px, prev_bottom, new_bottom):
        """下向きに動く足元が、このフレームで踏む面。(高さ, 地面か) の、一番高いもの。なければ None
        地面も足場も、上から降りてくるときだけ乗れる（下や横からは、通り抜ける・壁になる）"""
        x0, x1 = px - self.FOOT, px + self.FOOT
        best = None
        for a, b, top in self.ground:
            if a < x1 and x0 < b and prev_bottom <= top + 1 and new_bottom >= top:
                if best is None or top < best[0]:
                    best = (top, True)
        for a, b, top in self.platforms + self.lit + self.mover_now:
            if a < x1 and x0 < b and prev_bottom <= top + 1 and new_bottom >= top:
                if best is None or top < best[0]:
                    best = (top, False)
        return best

    def push_x(self, old_px, new_px, py, half):
        """横に動いた体が、地面の横の面（壁）にめり込んだら、押し戻した位置を返す。
        足元が、区間の上面より下にあるときだけ、その区間は壁になる（上を越えれば、壁ではない）。
        壁の中に入り込んでいたら、外へ押し出す"""
        px = new_px
        for a, b, top in self.ground:
            if top >= py - 0.5:
                continue
            if px - half < b and a < px + half:
                if old_px + half <= a + 0.01:
                    px = a - half
                elif old_px - half >= b - 0.01:
                    px = b + half
                else:
                    # すでに壁に入り込んでいる（角をかすめて落ちると、足は乗れないのに、体の端だけ区間に重なる）。
                    # そのままだと壁をすり抜けて、地面の下へ落ちるので、近い側へ押し出す
                    px = a - half if px < (a + b) / 2 else b + half
        return px

    def safe_spot(self, px, y, margin=24):
        """(px, y) が、区間の端から margin 以上離れた地面の上なら True（穴に落ちたときに戻る場所の候補）"""
        return any(a + margin <= px <= b - margin and abs(top - y) < 1 for a, b, top in self.ground)


