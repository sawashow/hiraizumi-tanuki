def thin_dango(items, platforms):
    """団子を間引く。団子は、手裏剣を投げられる数を増やす物になったので、数を絞る（画面に、物が多すぎないように）。
    **足場の上の団子だけを残す（足場1つに、1つ）。地面に置いた団子は、すべて外す。**
    足場に乗る理由が、団子になる（団子を外した足場は、乗る意味が無くなる）。ほかのアイテムは、そのまま"""
    out, used = [], set()
    for it in items:
        if it[0] != "dango":
            out.append(it)
            continue
        on = [p for p in platforms if p[0] - 6 <= it[1] <= p[1] + 6 and 0 < p[2] - it[2] <= 60]
        if on and on[0] not in used:
            used.add(on[0])
            out.append(("dango", (on[0][0] + on[0][1]) // 2, it[2]))    # 足場の真ん中に置く
    return tuple(out)


class StageDef:
    """1つの面のデータ。地形・アイテム・敵・ボス・背景・曲を、1つにまとめる。
    絵は assets/images 以下の相対パス。面ごとの絵が無ければ、1面の絵で代わりにする"""

    def __init__(self, name, width, ground, platforms, items, checkpoint, spawns, bgm, bgm_boss,
                 sky="bg_sky.png", mid="bg_mid.png", tiles="", boss_x=None,
                 boss_title=C.BOSS_TITLE, boss_name=C.BOSS_NAME, boss_pattern=C.BOSS_PATTERN,
                 talk_boss=C.TALK_BOSS, talk_tanuki=C.TALK_TANUKI, number=1, stele_x=150, boss_kind="boss", pit=(8, 6, 18), gates=(), lanterns=(), zones=(), gilt=False, haze=None, winds=(), traps=(), thought=(), pit_deep=None, climb=None):
        self.name, self.width = name, width
        self.climb = climb      # 崖登り: (左端, 右端, 高さ)。Terrain の climb を見よ
        self.ground, self.platforms, self.items = ground, platforms, items
        self.checkpoint, self.spawns = checkpoint, spawns
        self.bgm, self.bgm_boss = bgm, bgm_boss
        self.sky, self.mid, self.tiles = sky, mid, tiles   # tiles は、タイルの入ったフォルダ（空なら、直下）
        self.boss_x = boss_x if boss_x is not None else width - 110   # ボスが降ってくる場所
        self.boss_title, self.boss_name, self.boss_pattern = boss_title, boss_name, boss_pattern
        self.talk_boss, self.talk_tanuki = talk_boss, talk_tanuki
        self.boss_kind = boss_kind   # boss=泰衡（落ち武者） / boss2=基衡
        self.number = number    # 第N面（面の名前・石碑の絵の番号）
        self.stele_x = stele_x  # 石碑を置く場所
        self.pit = pit          # 穴の底の色（池の絵があれば、そちらを出す）
        self.lanterns = tuple(lanterns)   # 石灯籠: (中の物, x)。壊すと、中の物が出る。団子は入れない（団子の数に、数えていないため）
        # 区画（面の設計）: (左端, 右端, 名前, 役目, ねらいの強さ 1〜5)。役目は config.ZONE_ROLES。遊びには使わない。
        # tools/difficulty.py が、区画ごとに、実際の強さを測って、ねらいと比べる
        self.zones = tuple(zones)
        self.pit_deep = pit_deep    # 穴の、いちばん下の色（None なら、pit の一色）。下へ行くほど、この色に近づく
        self.haze = haze        # 穴の上の「もや」の高さ（None なら、config.PIT_HAZE の h）。空が明るい面では、低くする
        # 面ごとの仕掛け（その面だけの遊び。同じ敵と地形の繰り返しに、ならないように）
        self.winds = tuple(winds)   # 山おろし: (左端, 右端, 間隔のフレーム数)。右端から、風が、地面ぞいに吹き下ろす
        self.traps = tuple(traps)   # 光の柱の廊下: (左端, 右端, 柱の間隔, 一巡りのフレーム数)。床の印の所に、左から順に、光の柱が落ちる
        # ボスを倒したあと、タヌキ侍が、返事の代わりに、頭に思い浮かべる物（アイテムの名前。順に出る）。空なら、せりふ（talk_tanuki）で返す
        self.thought = tuple(thought)
        self.gilt = gilt        # 堂の中の面: 石の小物（石灯籠）を、金に塗り替えて出す
        self.gates = tuple(gates)   # 面の途中の「ボスの間」（影のボス）: (左端の x, ボスの種類)。最後のボスの間は、面の端

    @property
    def arenas(self):
        """ボスの間の一覧（遊ぶ順）。途中の間（影のボス）と、最後の間（面の端。倒すと、クリア）"""
        out = [dict(x0=x, x1=x + C.BASE_W, boss_x=x + C.BASE_W - 110, kind=k, shadow=True) for x, k in self.gates]
        out.append(dict(x0=self.arena_x0, x1=self.width, boss_x=self.boss_x, kind=self.boss_kind, shadow=False))
        return out

    @property
    def arena_x0(self):
        """ボスの場所の左端（ここで画面が止まる）"""
        return self.width - C.BASE_W

    @property
    def end_boss_x(self):
        """倒したボスが、吹っ飛んで倒れる場所"""
        return self.boss_x

    @property
    def end_tanuki_x(self):
        """寸劇で、タヌキ侍が話すときに立つ場所"""
        return self.arena_x0 + C.BOSS_TRIGGER + 20

    @property
    def dango_total(self):
        return sum(1 for k, _, _ in self.items if k == "dango")

    def terrain(self):
        return Terrain(self.ground, self.platforms, self.climb)


